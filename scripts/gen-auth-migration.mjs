// Prints the D1 migration for the installed Better Auth version and our auth options.
// Usage: pnpm gen:auth-migration > migrations/0001_auth.sql
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { runnerImport } from "vite";

// Loaded through Vite so this works on Node builds without TypeScript support.
const {
  module: { authOptions },
} = await runnerImport(new URL("../src/worker/auth.ts", import.meta.url).pathname, { configFile: false });

const placeholderEnv = {
  BETTER_AUTH_URL: "http://localhost:5173",
  BETTER_AUTH_SECRET: "schema-generation-only-not-a-real-secret",
  GOOGLE_CLIENT_ID: "unused",
  GOOGLE_CLIENT_SECRET: "unused",
  INSTRUCTOR_EMAILS: "",
};
const { compileMigrations } = await getMigrations(
  authOptions(placeholderEnv, new DatabaseSync(":memory:")),
);
process.stdout.write(`-- Generated by scripts/gen-auth-migration.mjs. Do not edit by hand.\n${await compileMigrations()}\n`);
